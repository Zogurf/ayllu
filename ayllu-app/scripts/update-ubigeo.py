"""Import the pinned CC0 Ubigeos Peru snapshot and generate its Postgres seed.
Run from any directory: python3 scripts/update-ubigeo.py
"""
import json
import re
import urllib.request
from pathlib import Path

COMMIT = '23cd3666b19f32bccdf36d90243c2a4462d6202c'
BASE = f'https://raw.githubusercontent.com/RitchieRD/ubigeos-peru-data/{COMMIT}/'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/data/ubigeo'
OUT.mkdir(parents=True, exist_ok=True)

def fetch(name):
    return urllib.request.urlopen(BASE + name, timeout=30).read()

def load(name, key):
    return json.loads(fetch('json/' + name))[key]

departments = load('1_ubigeo_departamentos.json', 'ubigeo_departamentos')
provinces = load('2_ubigeo_provincias.json', 'ubigeo_provincias')
districts = load('3_ubigeo_distritos.json', 'ubigeo_distritos')
dep_by_id = {r['id']: r for r in departments}
prov_by_id = {r['id']: r for r in provinces}
for rows, digits in [(departments, 2), (provinces, 4), (districts, 6)]:
    assert len({r['ubigeo'] for r in rows}) == len(rows), 'Duplicate codes'
    assert all(re.fullmatch(r'\d{' + str(digits) + '}', r['ubigeo']) for r in rows)
for p in provinces:
    assert p['ubigeo'][:2] == dep_by_id[p['departamento_id']]['ubigeo']
for d in districts:
    p = prov_by_id[d['provincia_id']]
    assert p['departamento_id'] == d['departamento_id']
    assert d['ubigeo'][:4] == p['ubigeo']

catalog = {
    'departments': [{'code': r['ubigeo'], 'name': r['departamento']} for r in departments],
    'provinces': [{'code': r['ubigeo'], 'name': r['provincia'], 'departmentCode': r['ubigeo'][:2]} for r in provinces],
    'districts': [{'code': r['ubigeo'], 'name': r['distrito'], 'provinceCode': r['ubigeo'][:4]} for r in districts],
}
(OUT / 'catalog.json').write_text(json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + '\n')
(OUT / 'LICENSE').write_bytes(fetch('LICENSE'))
(OUT / 'SOURCE.md').write_text(f'''# Ubigeos Perú

Source: https://github.com/RitchieRD/ubigeos-peru-data
Commit: `{COMMIT}`
License: CC0-1.0 (see LICENSE).
Imported: {len(departments)} departments, {len(provinces)} provinces, {len(districts)} districts.

Generated from the three JSON files in the source repository. Codes are strings,
not the source's numeric IDs. Names are preserved as published. This is a pinned
community catalog, not a live guarantee of administrative completeness.
Regenerate with `python3 ayllu-app/scripts/update-ubigeo.py` from the repo root.
If updating after deployment, ship the SQL changes in a new migration.
''')

def quote(value):
    return "'" + value.replace("'", "''") + "'"

values = []
for d in districts:
    p = prov_by_id[d['provincia_id']]
    dep = dep_by_id[d['departamento_id']]
    values.append('(' + ', '.join(map(quote, [d['ubigeo'], dep['departamento'], p['provincia'], d['distrito']])) + ')')
seed = '''-- Generated by ayllu-app/scripts/update-ubigeo.py; CC0 source documented in src/data/ubigeo/SOURCE.md.
create table public.peru_districts (
  ubigeo text primary key check (ubigeo ~ '^[0-9]{6}$'),
  department text not null,
  province text not null,
  district text not null
);
alter table public.peru_districts enable row level security;
revoke all on public.peru_districts from anon, authenticated;
grant select on public.peru_districts to authenticated;
create policy "authenticated users can read ubigeos" on public.peru_districts
  for select to authenticated using (true);

insert into public.peru_districts (ubigeo, department, province, district) values
'''
seed += ',\n'.join(values) + '\non conflict (ubigeo) do update set department = excluded.department, province = excluded.province, district = excluded.district;\n'
(ROOT.parent / 'supabase/migrations/202611080001_peru_ubigeo_catalog.sql').write_text(seed)
print(f'Imported {len(departments)} departments, {len(provinces)} provinces, {len(districts)} districts')
